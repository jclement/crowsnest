// The terminals' font chain (DESIGN.md 12, "Terminal font"). It copies Jeff's Ghostty config:
//
//   font-family = JetBrainsMono Nerd Font Mono   → local() only: used when it is installed
//   (JetBrains Mono Variable, self-hosted)       → the same letters when it is not (phones)
//   (Symbols Nerd Font Mono)                     → powerline, devicons, prompt icons
//   font-family = DejaVu Sans Mono               → box drawing, arrows, technical symbols
//   font-family = Noto Sans Math                 → maths
//   font-family = Noto Sans Symbols 2            → braille, legacy-computing and other symbols
//
// The fallbacks are self-hosted, cut into chunks by unicode-range, so a browser fetches a chunk
// only when one of its characters is on screen (fonts/terminal/terminal-fonts.css, generated by
// web/scripts/terminal-fonts.py). Characters whose default look is emoji are in none of them and
// fall through to the system's colour emoji font. Only XTerm.tsx uses this; code blocks elsewhere
// keep the plain monospace stack.
//
// xterm.js measures its cell from the font when it opens, and caches each glyph's width as it
// first draws it (to keep fallback glyphs on the grid). So the primary faces are loaded before
// the terminal opens, and every later font arrival (a fallback chunk, fetched when its first
// glyph is drawn) makes the terminal measure again.

/** The CSS families, in order. The generated CSS declares the faces under these names. */
export const TERMINAL_FONT_FAMILIES = [
  "JetBrainsMono Nerd Font Mono",
  "JetBrains Mono Variable",
  "Symbols Nerd Font Mono",
  "DejaVu Sans Mono",
  "Noto Sans Math",
  "Noto Sans Symbols 2",
] as const;

/** The font-family value for the terminal: the chain, then the platform's monospace. */
export const TERMINAL_FONT_FAMILY = [
  ...TERMINAL_FONT_FAMILIES.map((family) => `"${family}"`),
  "ui-monospace",
  "SFMono-Regular",
  "Menlo",
  "Consolas",
  "monospace",
].join(", ");

/** How long the terminal waits for its text font before opening with whatever is there. */
export const FONT_WAIT_MS = 2_000;

/**
 * Resolves once the text faces (regular and bold, at this size) are loaded or have failed, or
 * after timeoutMs: a slow font must not keep the terminal from opening, and the terminal
 * re-measures when the font does arrive (watchFontLoads).
 */
export async function loadTerminalFonts(size: number, timeoutMs = FONT_WAIT_MS): Promise<void> {
  const fonts = typeof document === "undefined" ? undefined : document.fonts;
  if (!fonts) return;
  const loads = ["JetBrainsMono Nerd Font Mono", "JetBrains Mono Variable"].flatMap((family) =>
    ["", "bold "].map((weight) => fonts.load(`${weight}${size}px "${family}"`).catch(() => [])),
  );
  let timer: ReturnType<typeof setTimeout> | undefined;
  const timeout = new Promise<void>((resolve) => {
    timer = setTimeout(resolve, timeoutMs);
  });
  await Promise.race([Promise.all(loads), timeout]);
  clearTimeout(timer);
}

/**
 * Calls onLoaded (at most once a frame) whenever the document finishes loading fonts. Returns
 * the unsubscribe function.
 */
export function watchFontLoads(onLoaded: () => void): () => void {
  const fonts = typeof document === "undefined" ? undefined : document.fonts;
  if (!fonts?.addEventListener) return () => {};
  let frame = 0;
  const handler = () => {
    cancelAnimationFrame(frame);
    frame = requestAnimationFrame(onLoaded);
  };
  fonts.addEventListener("loadingdone", handler);
  return () => {
    cancelAnimationFrame(frame);
    fonts.removeEventListener("loadingdone", handler);
  };
}

/**
 * The two spellings of the font family the terminal alternates between to make xterm.js measure
 * again: it ignores an option set to the value it already has, and a font that arrived does not
 * change the value. The trailing space changes the string, not the CSS.
 */
export const TERMINAL_FONT_FAMILY_SPELLINGS = [TERMINAL_FONT_FAMILY, `${TERMINAL_FONT_FAMILY} `] as const;

/** The other spelling of the family: what to set to force a re-measure. */
export function otherSpelling(current: string): string {
  return current === TERMINAL_FONT_FAMILY_SPELLINGS[0] ? TERMINAL_FONT_FAMILY_SPELLINGS[1] : TERMINAL_FONT_FAMILY_SPELLINGS[0];
}
